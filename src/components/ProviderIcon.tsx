export function ProviderIcon({
  icon,
  name,
  color,
  size = 32,
  className,
  showFallback = true,
}: ProviderIconProps) {
  const sizeStyle = useMemo(() => {
    const sizeValue = typeof size === "number" ? `${size}px` : size;
    return {
      width: sizeValue,
      height: sizeValue,
      fontSize: sizeValue,
      lineHeight: 1,
    };
  }, [size]);

  const appIcon =
    icon === "claude" ? (
      <ClaudeIcon />
    ) : icon === "openai" ? (
      <OpenAiIcon />
    ) : icon === "gemini" ? (
      <GeminiIcon />
    ) : icon === "grok" ? (
      <GrokIcon />
    ) : icon === "opencode" ? (
      <OpenCodeIcon />
    ) : icon === "openclaw" ? (
      <OpenClawIcon />
    ) : null;

  if (appIcon) {
    return (
      <span
        aria-hidden="true"
        className={cn(
          "inline-flex flex-shrink-0 items-center justify-center",
          className,
        )}
        title={name}
        style={{ ...sizeStyle, color }}
      >
        {appIcon}
      </span>
    );
  }

  if (!showFallback) return null;
  const initials = name
    .split(" ")
    .map((word) => word[0])
    .join("")
    .toUpperCase()
    .slice(0, 2);

  return (
    <span
      aria-hidden="true"
      className={cn(
        "inline-flex flex-shrink-0 items-center justify-center rounded-lg",
        "bg-muted font-semibold text-muted-foreground",
        className,
      )}
      title={name}
      style={sizeStyle}
    >
      <span
        style={{
          fontSize:
            typeof size === "number"
              ? `${Math.max(size * 0.5, 12)}px`
              : "0.5em",
        }}
      >
        {initials}
      </span>
    </span>
  );
}
